package co.antesdeabrir.piloto;

import android.content.Context;
import android.content.SharedPreferences;
import android.os.SystemClock;
import com.google.firebase.FirebaseApp;
import com.google.firebase.perf.FirebasePerformance;
import com.google.firebase.perf.metrics.Trace;
import org.json.JSONArray;
import org.json.JSONObject;
import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;
import java.util.UUID;

/**
 * Privacy-first performance instrumentation for the Android pilot.
 * Local metrics always work; remote SDK traces require a registered Android Firebase app
 * (android/app/google-services.json) and a separate, explicit opt-in.
 * No URLs, domains, message text, names, room codes or Firebase auth tokens are recorded.
 */
public final class NativePerformance {
    private NativePerformance() {}
    private static final String PREF = "smartguard_android_performance_v061";
    private static final String[] KINDS = {
        "app_ready", "manual_analysis", "notification_analysis", "family_create",
        "family_join", "family_manual", "family_upload"
    };
    private static final int MAX_RECENT = 64;
    private static final long MAX_DURATION_MS = 10L * 60L * 1000L;
    private static final Map<String, Ticket> ACTIVE = new HashMap<>();
    private static volatile long launchAt = 0L;
    private static volatile boolean launchRecorded = false;

    public static final class Ticket {
        private final String id;
        private final String kind;
        private final long startedAt;
        private final Trace remote;
        private Ticket(String id, String kind, long startedAt, Trace remote) {
            this.id = id; this.kind = kind; this.startedAt = startedAt; this.remote = remote;
        }
    }

    private static SharedPreferences prefs(Context context) {
        return context.getApplicationContext().getSharedPreferences(PREF, Context.MODE_PRIVATE);
    }
    private static boolean allowedKind(String kind) {
        for (String name : KINDS) if (name.equals(kind)) return true;
        return false;
    }
    /** Called before the Capacitor Activity initializes its web content. */
    public static void noteLaunch() { launchAt = SystemClock.elapsedRealtime(); launchRecorded = false; }

    /**
     * google_app_id is generated by the Google Services Gradle plugin from the
     * Android app registration. The existing Firebase Web app ID is NOT interchangeable.
     */
    public static boolean firebaseReady(Context context) {
        try {
            Context app = context.getApplicationContext();
            int resource = app.getResources().getIdentifier("google_app_id", "string", app.getPackageName());
            if (resource == 0) return false;
            String id = app.getString(resource);
            if (!id.matches("1:[0-9]+:android:[a-zA-Z0-9]+")) return false;
            FirebaseApp initialized = FirebaseApp.initializeApp(app);
            if (initialized == null) return false;
            return id.equals(initialized.getOptions().getApplicationId())
                && "smartguard-piloto-20261029".equals(initialized.getOptions().getProjectId());
        } catch (Exception ignored) { return false; }
    }
    public static void initialize(Context context) {
        if (!firebaseReady(context)) return;
        try {
            FirebasePerformance.getInstance().setPerformanceCollectionEnabled(prefs(context).getBoolean("sharing", false));
        } catch (Exception ignored) { /* Local measurement continues if SDK cannot start. */ }
    }
    public static synchronized boolean setSharing(Context context, boolean value) {
        // Store a user's preference even before this APK has an Android Firebase
        // app registration; NEVER report an upload as active when it is not.
        boolean configured = firebaseReady(context);
        if (!value) {
            try {
                if (configured) FirebasePerformance.getInstance().setPerformanceCollectionEnabled(false);
                prefs(context).edit().putBoolean("sharing", false).putBoolean("sharingRequested", false).apply();
                return true;
            } catch (Exception ignored) { return false; }
        }
        if (!configured) {
            prefs(context).edit().putBoolean("sharingRequested", true).putBoolean("sharing", false).apply();
            return true;
        }
        try {
            FirebasePerformance.getInstance().setPerformanceCollectionEnabled(true);
            prefs(context).edit().putBoolean("sharingRequested", true).putBoolean("sharing", true).apply();
            return true;
        } catch (Exception ignored) { return false; }
    }
    private static boolean canUpload(Context context) {
        return prefs(context).getBoolean("sharing", false) && firebaseReady(context);
    }
    public static Ticket begin(Context context, String kind) {
        if (!allowedKind(kind)) throw new IllegalArgumentException("Unknown metric name");
        Trace trace = null;
        if (canUpload(context)) {
            try { trace = FirebasePerformance.getInstance().newTrace("sg_" + kind); trace.start(); }
            catch (Exception ignored) { trace = null; }
        }
        return new Ticket(UUID.randomUUID().toString(), kind, SystemClock.elapsedRealtime(), trace);
    }
    public static synchronized String start(Context context, String kind) {
        if (ACTIVE.size() >= 32) {
            // Close long-running or abandoned spans to avoid unbounded memory usage.
            for (Ticket abandoned : ACTIVE.values()) {
                if (abandoned.remote != null) try { abandoned.remote.stop(); } catch (Exception ignored) {}
            }
            ACTIVE.clear();
        }
        Ticket ticket = begin(context, kind);
        ACTIVE.put(ticket.id, ticket);
        return ticket.id;
    }
    public static synchronized boolean stop(Context context, String id, boolean success) {
        Ticket ticket = ACTIVE.remove(id);
        if (ticket == null) return false;
        finish(context, ticket, success);
        return true;
    }
    public static void finish(Context context, Ticket ticket, boolean success) {
        if (ticket == null) return;
        long elapsed = Math.max(0L, SystemClock.elapsedRealtime() - ticket.startedAt);
        record(context, ticket.kind, elapsed, success);
        if (ticket.remote != null) {
            try {
                ticket.remote.putAttribute("result", success ? "ok" : "error");
                if (!success) ticket.remote.incrementMetric("errors", 1);
                ticket.remote.stop();
            } catch (Exception ignored) { /* Don't interrupt protection or uploads. */ }
        }
    }
    /** For pre-existing async code that already has an elapsed time. */
    public static void record(Context context, String kind, long durationMs, boolean success) {
        if (!allowedKind(kind)) return;
        long safe = Math.min(MAX_DURATION_MS, Math.max(0L, durationMs));
        SharedPreferences p = prefs(context);
        synchronized (NativePerformance.class) {
            try {
                JSONObject state = new JSONObject(p.getString(kind, "{}"));
                JSONArray previous = state.optJSONArray("recent");
                JSONArray recent = new JSONArray();
                int start = previous == null ? 0 : Math.max(0, previous.length() - MAX_RECENT + 1);
                if (previous != null) for (int i = start; i < previous.length(); i++) recent.put(previous.optLong(i));
                recent.put(safe);
                state.put("recent", recent);
                state.put("count", state.optLong("count", 0) + 1);
                state.put("totalMs", state.optLong("totalMs", 0) + safe);
                state.put("maxMs", Math.max(state.optLong("maxMs", 0), safe));
                state.put("lastMs", safe);
                state.put("lastAt", System.currentTimeMillis());
                state.put("errors", state.optLong("errors", 0) + (success ? 0 : 1));
                p.edit().putString(kind, state.toString()).apply();
            } catch (Exception ignored) { /* Metrics must never break SmartGuard. */ }
        }
    }
    /** Called once when the React screen first becomes available. */
    public static synchronized void markUiReady(Context context) {
        if (launchRecorded || launchAt <= 0) return;
        launchRecorded = true;
        // Local-only cold-UI start: SDK's automatic app-start metrics are independent.
        record(context, "app_ready", SystemClock.elapsedRealtime() - launchAt, true);
    }
    public static JSONObject status(Context context) {
        SharedPreferences p = prefs(context);
        JSONObject result = new JSONObject();
        JSONObject metrics = new JSONObject();
        try {
            for (String kind : KINDS) {
                JSONObject state = new JSONObject(p.getString(kind, "{}"));
                long count = state.optLong("count", 0);
                JSONArray recent = state.optJSONArray("recent");
                int n = recent == null ? 0 : recent.length();
                long[] values = new long[n];
                for (int i = 0; i < n; i++) values[i] = recent.optLong(i);
                Arrays.sort(values);
                long p95 = n == 0 ? 0 : values[Math.max(0, (int)Math.ceil(n * 0.95) - 1)];
                metrics.put(kind, new JSONObject()
                    .put("count", count)
                    .put("averageMs", count == 0 ? 0 : state.optLong("totalMs") / count)
                    .put("p95Ms", p95)
                    .put("maxMs", state.optLong("maxMs", 0))
                    .put("lastMs", state.optLong("lastMs", 0))
                    .put("lastAt", state.optLong("lastAt", 0))
                    .put("errors", state.optLong("errors", 0)));
            }
            result.put("metrics", metrics);
            result.put("firebaseReady", firebaseReady(context));
            result.put("sharing", p.getBoolean("sharing", false) && firebaseReady(context));
            result.put("sharingRequested", p.getBoolean("sharingRequested", p.getBoolean("sharing", false)));
            result.put("project", "smartguard-piloto-20261029");
            result.put("version", context.getPackageManager().getPackageInfo(context.getPackageName(), 0).versionName);
            result.put("description", "Métricas técnicas sin URLs, mensajes, dominios ni nombres de familiares");
        } catch (Exception ignored) { }
        return result;
    }
}
