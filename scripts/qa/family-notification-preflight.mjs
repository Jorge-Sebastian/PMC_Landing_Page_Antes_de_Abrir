/** Verifies the notification flow remains connected to Family instead of linking to unsafe sites. */
import fs from 'node:fs';
import assert from 'node:assert/strict';
const text = name => fs.readFileSync(name, 'utf8');
const alerts = text('android/app/src/main/java/co/antesdeabrir/piloto/Alerts.java');
const listener = text('android/app/src/main/java/co/antesdeabrir/piloto/MessageListenerService.java');
const reporter = text('android/app/src/main/java/co/antesdeabrir/piloto/FirebaseFamilyReporter.java');
const details = text('src/mobile/notification-details.tsx');
const session = text('src/mobile/family-session-bootstrap.tsx');
const family = text('src/pages/familia/index.tsx');
const app = text('src/App.tsx');
const gradle = text('android/app/build.gradle');
assert.match(listener, /FirebaseFamilyReporter\.lookup\(this,url\)/);
assert.match(listener, /familyLookups\.execute/);
assert.match(listener, /Alerts\.familyLookupFinished\(this,id,url,matches\)/);
assert.match(alerts, /familyLookupPending/);
assert.match(alerts, /static void familyLookupFinished/);
assert.match(reporter, /family_rooms\/.*:runQuery|rootPath \+ ":runQuery"/);
assert.match(reporter, /uid\.equals\(reportedBy\)/);
assert.match(reporter, /member\.optJSONObject\("shareRisks"\)/);
assert.match(reporter, /room\.equals\(p\.getString\("room"/);
assert.match(reporter, /if \(events\.code != 200\) return null/);
assert.match(alerts, /familyHeading="ALERTA FAMILIAR/);
assert.match(alerts, /familyExplanation/);
assert.match(alerts, /String originalSummary/);
assert.match(alerts, /\.setContentIntent\(open\)/);
assert.match(alerts, /Ver alerta familiar/);
assert.doesNotMatch(alerts, /Intent\.ACTION_VIEW/);
const firstFamily = details.indexOf('detail.familyMatches?.length');
const firstGeneric = details.indexOf('<DecisionCard detail={detail} />');
assert.ok(firstFamily >= 0 && firstFamily < firstGeneric, 'Family match must precede generic reasons in detail');
assert.match(session, /stored.*sg:family-room-code:v1/);
assert.match(session, /share:member\.shareRisks===true/);
assert.match(family, /share:sharingAllowed/);
assert.match(app, /<FamilySessionBootstrap \/>/);
assert.match(gradle, /versionCode 21/);
console.log('Family notification preflight PASS: Firebase lookup, priority, tap, privacy and version.');
