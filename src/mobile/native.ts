import { Capacitor, registerPlugin } from '@capacitor/core';
import type { MessageFinding } from '@/lib/link-analysis/message-analysis';
import type { Decision, ExtraChecks } from '@/lib/link-analysis/notification-decision';
import type { DestinationCheck, Verdict } from '@/lib/link-analysis/types';

export const isAndroidPilot = Capacitor.getPlatform() === 'android';
export type FamilyNotificationMatch = {kind:'same-domain'|'similar-domain';memberNickname:string;registrableDomain:string;observedAt?:string};
export type Detail = { familyMatches?: FamilyNotificationMatch[]; id: number; pending: boolean; test: boolean; url: string; verdict?: Verdict; destination?: DestinationCheck | null; messageSignals?: MessageFinding[]; privacy?: { sensitive: boolean; reason?: string }; decision?: Decision; extra?: ExtraChecks };
export type ProtectionStatus = { enabled: boolean; access: boolean; notifications: boolean; showAll: boolean; processed: number; lastAt: number; apps: Record<string, boolean>; historyEnabled: boolean; history: Array<{ color: string; domain: string; date: number }>; feedbackCount: number; externalReady: boolean; rulesVersion: string };
export type DeviceMetric = {count:number;averageMs:number;p95Ms:number;maxMs:number;lastMs:number;lastAt:number;errors:number};
export type DevicePerformanceStatus = {
  firebaseReady:boolean; sharing:boolean; sharingRequested:boolean; project:string; version:string; description:string;
  metrics:Record<string,DeviceMetric>;
};
export const Protection = registerPlugin<{
  status(): Promise<ProtectionStatus>;
  activate(): Promise<void>;
  pause(): Promise<void>;
  alertSettings(): Promise<void>;
  setApp(options: { app: string; value: boolean }): Promise<void>;
  setHistory(options: { value: boolean }): Promise<void>;
  clearHistory(): Promise<void>;
  reportResult(options: { id: number; expected: string }): Promise<void>;
  exportFeedback(): Promise<void>;
  setShowAll(options: { value: boolean }): Promise<void>;
  testBanner(options: { level: string }): Promise<void>;
  openedAnalysis(): Promise<{ detail: Detail | null }>;
  recheckAnalysis(options: { id: number }): Promise<void>;
  closeAnalysis(): Promise<void>;
  copyDomain(options: { domain: string }): Promise<void>;
  firebaseBackgroundSession(options: {uid:string;refreshToken:string;colors:boolean;share:boolean;version:string}):Promise<{enabled:boolean;pending:number}>;
  firebaseBackgroundStatus():Promise<{active:boolean;pending:number;error?:string;needsReconnection?:boolean}>;
  firebaseBackgroundStop():Promise<void>;
  firebaseFamilySession(options:{uid:string;refreshToken:string;code:string;share:boolean}):Promise<{active:boolean;pending:number}>;
  firebaseFamilyStatus():Promise<{active:boolean;room:string;pending:number;error?:string}>;
  firebaseFamilyStop():Promise<void>;
  performanceStatus():Promise<DevicePerformanceStatus>;
  performanceSharing(options:{enabled:boolean}):Promise<DevicePerformanceStatus>;
  performanceStart(options:{kind:'manual_analysis'|'family_join'|'family_create'|'family_manual'}):Promise<{ticket:string}>;
  performanceStop(options:{ticket:string;success:boolean}):Promise<{recorded:boolean}>;
  performanceUiReady():Promise<void>;
}>('Protection');
